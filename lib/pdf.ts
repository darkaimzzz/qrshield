"use client"

import type { Report } from "@/lib/engine/types"
import { BAND_STYLE, CATEGORY_LABEL, SOURCE_LABEL } from "@/lib/risk-ui"

/** jsPDF's built-in Helvetica only covers Latin-1; map typographic characters and drop the rest. */
function latin1(s: string): string {
  return s
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[→]/g, "->")
    .replace(/[\u2013\u2014]/g, "-") // en and em dashes
    .replace(/…/g, "...")
    .replace(/[^\x00-\xFF]/g, "?")
}

/** Builds a text-based PDF report (selectable text, real evidence and timestamps). */
export async function downloadReportPdf(report: Report) {
  const { jsPDF } = await import("jspdf")
  const doc = new jsPDF({ unit: "pt", format: "a4" })
  const W = doc.internal.pageSize.getWidth()
  const H = doc.internal.pageSize.getHeight()
  const M = 44
  let y = 0

  const ensure = (h: number) => {
    if (y + h > H - M) {
      doc.addPage()
      y = M
    }
  }
  const text = (
    s: string,
    opts: {
      size?: number
      bold?: boolean
      color?: [number, number, number]
      indent?: number
      mono?: boolean
    } = {},
  ) => {
    const size = opts.size ?? 10
    doc.setFont(opts.mono ? "courier" : "helvetica", opts.bold ? "bold" : "normal")
    doc.setFontSize(size)
    doc.setTextColor(...(opts.color ?? [30, 41, 59]))
    const lines = doc.splitTextToSize(latin1(s), W - 2 * M - (opts.indent ?? 0)) as string[]
    for (const line of lines) {
      ensure(size * 1.35)
      doc.text(line, M + (opts.indent ?? 0), y)
      y += size * 1.35
    }
  }
  const heading = (s: string) => {
    y += 10
    ensure(30)
    doc.setDrawColor(226, 232, 240)
    doc.line(M, y - 4, W - M, y - 4)
    y += 10
    text(s, { size: 12, bold: true, color: [8, 145, 178] })
    y += 2
  }
  const kv = (k: string, v: string) => {
    ensure(14)
    doc.setFont("helvetica", "normal")
    doc.setFontSize(9)
    doc.setTextColor(100, 116, 139)
    doc.text(latin1(k), M, y)
    const lines = doc.splitTextToSize(latin1(v), W - 2 * M - 130) as string[]
    doc.setTextColor(30, 41, 59)
    doc.setFont("courier", "normal")
    lines.forEach((l, i) => {
      ensure(12)
      doc.text(l, M + 130, y + (i === 0 ? 0 : 0))
      y += 12
    })
  }

  // Header band
  doc.setFillColor(6, 10, 19)
  doc.rect(0, 0, W, 78, "F")
  doc.setFont("helvetica", "bold")
  doc.setFontSize(18)
  doc.setTextColor(34, 211, 238)
  doc.text("QRShield", M, 36)
  doc.setFont("helvetica", "normal")
  doc.setFontSize(9)
  doc.setTextColor(203, 213, 225)
  doc.text("Security Analysis Report  |  Scan Smarter. Stay Safer.", M, 54)
  doc.text(`Report ID ${report.id}`, W - M, 36, { align: "right" })
  doc.text(`Generated ${new Date().toISOString()}`, W - M, 54, { align: "right" })
  y = 108

  const band = BAND_STYLE[report.band]
  const hex = band.hex.replace("#", "")
  const rgb: [number, number, number] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16)) as [
    number,
    number,
    number,
  ]
  text(`${report.score}/100  ${band.label}`, { size: 20, bold: true, color: rgb })
  y += 4
  text(report.explanation.summary, { size: 10.5 })
  if (report.explanation.generatedBy === "llm")
    text(`(Summary wording AI-generated by ${report.explanation.model})`, {
      size: 8,
      color: [100, 116, 139],
    })

  heading("Scan details")
  kv("Scanned at", report.createdAt)
  kv("Input source", SOURCE_LABEL[report.source])
  kv("Decoded content", report.input)
  kv("Normalized URL", report.parsed.normalized)
  kv("Final URL", report.redirects.finalUrl ?? "Not resolved")
  kv("Hostname", report.parsed.hostname)
  kv("Registrable domain", report.parsed.registrableDomain ?? "N/A")
  kv("HTTPS", report.parsed.protocol === "https:" ? "Yes" : "No")

  heading(`Threat indicators (${report.findings.length})`)
  if (!report.findings.length)
    text(
      "No risk indicators detected by the checks that ran. This does not prove the destination is safe.",
    )
  for (const f of report.findings) {
    y += 4
    text(
      `[${f.severity.toUpperCase()}] ${f.title}  (+${f.contribution}, ${CATEGORY_LABEL[f.category]})`,
      { bold: true, size: 10 },
    )
    text(f.explanation, { size: 9, color: [71, 85, 105], indent: 10 })
    for (const e of f.evidence) text(`- ${e}`, { size: 8.5, mono: true, indent: 10 })
  }

  heading("Redirect chain")
  if (!report.redirects.hops.length) text(report.redirects.detail)
  report.redirects.hops.forEach((h, i) =>
    text(
      `${i + 1}. [${h.status ?? "-"}] ${h.url}${h.crossDomain ? "  (cross-domain)" : ""}${h.error ? `  - ${h.error}` : ""}`,
      { size: 8.5, mono: true },
    ),
  )

  heading("Domain intelligence")
  const d = report.domain
  kv("Domain", d.domain ?? "N/A")
  kv("Registered", d.registrationDate ?? "Unavailable")
  kv("Age (days)", d.ageDays?.toString() ?? "Unavailable")
  kv("Registrar", d.registrar ?? "Unavailable")
  kv("Expires", d.expirationDate ?? "Unavailable")
  kv("Source", d.source ? `RDAP ${d.source}` : "None")
  text(d.detail, { size: 8.5, color: [100, 116, 139] })

  heading("Threat intelligence")
  for (const p of report.threatIntel.providers)
    text(`${p.name}: ${p.status.replace("_", " ")} - ${p.detail}`, { size: 9 })

  heading("Machine learning (separate from the risk score)")
  if (report.ml.probability !== null) {
    text(
      `Estimated phishing probability: ${(report.ml.probability * 100).toFixed(1)}% (${report.ml.modelName})`,
      { bold: true, size: 10 },
    )
  }
  text(report.ml.detail, { size: 9 })

  heading("Recommended actions")
  for (const r of report.explanation.recommendations) text(`- ${r}`, { size: 9.5 })

  heading("Checks & limitations")
  for (const c of report.checks) text(`${c.label}: ${c.status.replace("_", " ")}`, { size: 9 })
  y += 4
  for (const l of report.limitations) text(`- ${l}`, { size: 8.5, color: [100, 116, 139] })
  y += 8
  text(
    "A low score means few risk indicators were detected. It is not a guarantee of safety. No automated tool can verify that a website is safe.",
    { size: 8.5, bold: true, color: [100, 116, 139] },
  )

  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setFont("helvetica", "normal")
    doc.setFontSize(8)
    doc.setTextColor(148, 163, 184)
    doc.text(`QRShield report ${report.id.slice(0, 8)}  |  page ${i} of ${pages}`, W / 2, H - 20, {
      align: "center",
    })
  }
  doc.save(`qrshield-report-${report.parsed.hostname}-${report.createdAt.slice(0, 10)}.pdf`)
}

export function reportSummaryText(report: Report): string {
  return [
    `QRShield security report: ${report.score}/100 (${BAND_STYLE[report.band].label})`,
    `Scanned: ${report.createdAt}`,
    `URL: ${report.parsed.normalized}`,
    report.redirects.finalUrl && report.redirects.finalUrl !== report.parsed.normalized
      ? `Final URL: ${report.redirects.finalUrl}`
      : null,
    "",
    report.explanation.summary,
    "",
    "Findings:",
    ...(report.findings.length
      ? report.findings.map((f) => `- [${f.severity}] ${f.title} (+${f.contribution})`)
      : ["- none detected"]),
    "",
    "A low score is not a guarantee of safety.",
  ]
    .filter((x) => x !== null)
    .join("\n")
}
